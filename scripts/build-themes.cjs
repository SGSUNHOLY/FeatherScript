// Rebuild checked-in theme assets after editing core/theme-presets.json.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(process.argv[2] || path.join(__dirname, '..'));
const core = path.join(root, 'featherscript-extension/core');
const presets = JSON.parse(fs.readFileSync(path.join(core, 'theme-presets.json'), 'utf8'));
const original = [{ id: 'default', name: 'Default', light: true }, { id: 'dark', name: 'Dark' }, { id: 'midnight', name: 'Midnight' }];
const ids = new Set(original.map((p) => p.id));
function luminance(hex) {
  const rgb = hex.slice(1).match(/../g).map((v) => parseInt(v, 16) / 255).map((v) => v <= .04045 ? v / 12.92 : ((v + .055) / 1.055) ** 2.4);
  return rgb[0] * .2126 + rgb[1] * .7152 + rgb[2] * .0722;
}
function contrast(a, b) { const x = luminance(a), y = luminance(b); return (Math.max(x, y) + .05) / (Math.min(x, y) + .05); }
const desktop = [], overlay = [];
for (const p of presets) {
  if (!/^[a-z]+$/.test(p.id) || ids.has(p.id)) throw Error(`Invalid/duplicate theme: ${p.id}`);
  ids.add(p.id);
  for (const key of ['background', 'surface', 'accent', 'text', 'muted']) if (!/^#[\da-f]{6}$/i.test(p[key])) throw Error(`Invalid ${key}: ${p.id}`);
  for (const fg of ['text', 'muted', 'accent']) for (const bg of ['background', 'surface']) if (contrast(p[fg], p[bg]) < 4.5) throw Error(`Insufficient ${fg}/${bg} contrast: ${p.id}`);
  const line = p.light ? '#cbd5e1' : `${p.muted}45`;
  const vars = {
    paper: p.background, 'paper-hi': p.surface, 'paper-lo': p.background,
    ink: p.text, 'ink-soft': p.muted, 'ink-faint': p.muted,
    line, 'line-strong': p.muted, focus: `${p.accent}40`, 'btn-bg': p.accent, 'btn-ink': p.background,
    'card-bg': p.surface, 'card-solid': p.surface, 'card-edge': line,
    shadow: `0 24px 60px -30px ${p.light ? '#0f172a25' : '#000a'}`,
    sidebar: p.background, 'sidebar-text': p.text, 'sidebar-soft': p.muted,
    'sidebar-line': line, 'sidebar-active': `${p.accent}18`, workspace: p.background,
    panel: p.surface, 'panel-solid': p.surface, 'panel-text': p.text, 'panel-soft': p.muted, 'panel-line': line,
    accent: p.accent, 'accent-soft': p.accent,
    ok: p.light ? '#166534' : '#86efac', warn: p.light ? '#854d0e' : '#fde047', danger: p.light ? '#9f1239' : '#fda4af',
    'chip-bg': `${p.accent}12`, hover: `${p.accent}12`,
  };
  desktop.push(`body[data-theme="${p.id}"] {\n  color-scheme: ${p.light ? 'light' : 'dark'};\n${Object.entries(vars).map(([k,v]) => `  --${k}: ${v};`).join('\n')}\n}`);
  desktop.push(`.preview-${p.id} { background: ${p.surface}; }\n.preview-${p.id} .tp-side { background: ${p.background}; }\n.preview-${p.id} :is(.tp-bar, .tp-block) { background: ${p.accent}; }`);
  overlay.push(`html[data-zs-theme="${p.id}"] {\n  --zs-ink: ${p.text}; --zs-ink-soft: ${p.muted}; --zs-ink-line: ${line};\n  --zs-dark: ${p.background}; --zs-bar-1: ${p.surface}; --zs-bar-2: ${p.surface}; --zs-bar-3: ${p.background};\n  --zs-preset-surface: ${p.surface}; --zs-preset-background: ${p.background}; --zs-preset-accent: ${p.accent};\n}`);
}
const identities = JSON.parse(fs.readFileSync(path.join(core, 'theme-identities.json'), 'utf8'));
const presented = [...original, ...presets].map(p => ({...p, description: identities[p.id]?.description || p.description, identity: identities[p.id]?.label}));
const header = '/* Generated by scripts/build-themes.cjs; edit core/theme-presets.json. */\n';
fs.writeFileSync(path.join(core, 'theme-presets.js'), `// Generated by scripts/build-themes.cjs.\nglobalThis.FSThemePresets = Object.freeze(${JSON.stringify(presented, null, 2)}.map(Object.freeze));\n`);
fs.writeFileSync(path.join(root, 'featherscript-app/renderer/theme-presets.css'), header + desktop.join('\n') + '\n');
fs.writeFileSync(path.join(root, 'featherscript-extension/theme-presets.css'), header + overlay.join('\n') + `
html[data-zs-preset] :is(#zs-menu, #zs-setup, .zs-shot, .zs-chip) { background: var(--zs-preset-surface); color: var(--zs-ink); border-color: var(--zs-ink-line); }
html[data-zs-preset] :is(.zs-menu-note, .zs-menu-tag, #zs-set-status, #zs-setup-sub) { color: var(--zs-ink-soft); }
html[data-zs-preset] :is(#zs-set-text, .zs-mcp-item, .zs-mcp-input, .zs-chip-body) { background: var(--zs-preset-background); color: var(--zs-ink); border-color: var(--zs-ink-line); }
html[data-zs-preset] #zs-bar { border-color: var(--zs-preset-accent); background: linear-gradient(158deg,var(--zs-bar-1),var(--zs-bar-3)); box-shadow: 0 12px 30px #0003; }
html[data-zs-preset] #zs-bar::before { opacity: .12; animation: none; }
html[data-zs-preset] :is(.zs-brand, .zs-menu-logo, .zs-chip-title) { color: var(--zs-preset-accent); }
html[data-zs-preset] :is(#zs-root, #zs-bar) button { color: var(--zs-ink); background-color: var(--zs-preset-surface); border-color: var(--zs-ink-line); }
html[data-zs-preset] :is(#zs-root, #zs-bar) :focus-visible { outline: 2px solid var(--zs-preset-accent); outline-offset: 2px; }
`);
console.log(`Built ${presets.length} additional themes (${ids.size} total); text, muted and accent contrast all meet 4.5:1.`);

require('./build-theme-identities.cjs').build(root);
